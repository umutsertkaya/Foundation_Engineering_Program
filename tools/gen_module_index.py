"""Generate the deterministic module index, runnable from any working directory."""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES_DIR = ROOT / "geotek" / "modules"
HEADER = "# Generated by tools/gen_module_index.py; do not edit.\n"


def render_index(modules_dir: Path = MODULES_DIR) -> str:
    """Render public subpackages without importing module code."""
    ids = sorted(
        path.name for path in modules_dir.iterdir()
        if path.is_dir() and not path.name.startswith("_") and (path / "__init__.py").is_file()
    )
    declaration = "MODULE_IDS: tuple[str, ...] = ()\n"
    if ids:
        entries = "".join(f"    {id!r},\n" for id in ids)
        declaration = f"MODULE_IDS: tuple[str, ...] = (\n{entries})\n"
    return HEADER + "\nfrom __future__ import annotations\n\n" + declaration


def generate_module_index(modules_dir: Path = MODULES_DIR, *, check: bool = False) -> bool:
    """Write the index; in check mode return False if it is missing or stale."""
    output = modules_dir / "_index.py"
    content = render_index(modules_dir)
    if output.is_file() and output.read_bytes() == content.encode("utf-8"):
        return True
    if check:
        return False
    output.write_text(content, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the index would change")
    args = parser.parse_args()
    if not generate_module_index(check=args.check):
        print(f"Module index is stale: {MODULES_DIR / '_index.py'}")
        return 1
    print(MODULES_DIR / "_index.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
